<section class="container policies">
  <h1>Delivery and returns</h1>

  <article>
    <h2>Delivery</h2>
    <p class="updated">Last updated 14 November 2026.</p>

    <h3>1. Delivery charges</h3>
    <p>
      Delivery charges apply to all orders unless a free delivery promotion is advertised. The charge is shown
      at checkout before you pay. The total on that page is the amount you pay. Nothing is added afterwards.
    </p>
    <p>The charge can vary with the size, weight, and destination of the order.</p>

    <h3>2. Order processing and dispatch</h3>
    <p>Once payment is confirmed, we start preparing the order.</p>
    <p>
      Orders are dispatched with Royal Mail, or with another delivery partner when that is who we use for the
      parcel. We aim to dispatch promptly. The time can vary with what is in stock and how many orders are
      waiting.
    </p>

    <h3>3. Delivery tracking</h3>
    <p>
      Where the service is tracked, we pass on the tracking information once the order has been dispatched. You
      can follow the parcel with the delivery provider.
    </p>

    <h3>4. Delivery delays</h3>
    <p>
      We dispatch as promptly as we can. A parcel can still be delayed by the post, the weather, or another
      disruption we do not control. If it has not arrived in the time you expected, contact us with the order
      number and we will look into it.
    </p>

    <h3>5. Incorrect delivery information</h3>
    <p>
      You are responsible for the delivery details on the order. Check the address before you pay. If you spot
      a mistake, contact us as soon as you can. We cannot promise to change an address once the order has been
      processed or dispatched.
    </p>

    <h3>6. Contact us</h3>
    <p>
      For a delivery question, a missing parcel, or help with tracking, use
      <a href="/support">customer support</a> and include the order number.
    </p>
    <p>Nothing in this policy affects your statutory consumer rights.</p>
  </article>

  <article>
    <h2>Returns, refunds, and faulty goods</h2>
    <p class="updated">Last updated 14 November 2026.</p>
    <p>
      If something is not right, we will try to resolve it fairly and in line with UK consumer protection law.
    </p>

    <h3>1. Change of mind</h3>
    <p>
      If you buy online and change your mind, you generally have 14 days to cancel, starting the day after you
      receive the goods.
    </p>
    <ul>
      <li>Tell us you want to cancel within 14 days of receiving the order.</li>
      <li>Once you have told us, you have a further 14 days to send the item back.</li>
      <li>You may inspect an item as you would in a shop.</li>
      <li>
        You pay the direct cost of the return when you cancel because you changed your mind. This is made clear
        before you buy.
      </li>
      <li>
        Include the original packaging where you reasonably can. It is not an absolute requirement for the
        statutory right to cancel.
      </li>
    </ul>
    <p>
      If an item has been handled more than is reasonably needed to inspect it, we may deduct a reasonable
      amount from the refund for the loss in value, where the law allows that.
    </p>
    <p>Some products can be excluded from the right to cancel where a specific legal exception applies.</p>

    <h3>2. Faulty, damaged, or incorrect items</h3>
    <p>
      We take care that products are described accurately and sent in good condition. If an item arrives
      damaged or defective, does not work as it should, or is significantly different from the description or
      the photos, contact us as soon as you can. Include the order number and what is wrong. Photos help.
    </p>
    <p>
      Under the Consumer Rights Act 2015 you have rights when goods are faulty, not as described, or not fit
      for purpose.
    </p>
    <ul>
      <li>Within 30 days you generally have the right to reject faulty goods for a full refund.</li>
      <li>
        After 30 days you may be entitled to a repair or a replacement. If that does not work, or we cannot do
        it, you may be entitled to a refund or a price reduction.
      </li>
    </ul>
    <p>Where goods are faulty or not as described, Elboon covers reasonable return costs where the law requires it.</p>
    <p>
      Damage from misuse, an accident, or unreasonable handling after delivery is not automatically a defect.
    </p>

    <h3>3. Refunds</h3>
    <p>An approved refund is normally paid back the way you paid.</p>
    <p>
      For a change-of-mind cancellation, the refund includes the standard delivery charge you paid, where the
      law requires that. An extra charge for a premium delivery service may not be refunded.
    </p>
    <p>
      For an eligible change-of-mind cancellation, the refund is issued within 14 days of us receiving the
      goods back, or of receiving proof that you have sent them, whichever comes first.
    </p>
    <p>For faulty goods, the refund is processed within the statutory time.</p>

    <h3>4. Items excluded from a change-of-mind return</h3>
    <p>
      Some products can be exempt from the usual 14-day cancellation right, where the law says so. That can
      include:
    </p>
    <ul>
      <li>Personalised or custom-made products.</li>
      <li>Sealed hygiene products, once the seal is broken.</li>
      <li>Perishable goods.</li>
    </ul>
    <p>Those exclusions apply only where the legal conditions are met.</p>
    <p>They do not affect your statutory rights if an item is faulty, damaged, or not as described.</p>

    <h3>5. How to ask for a return or a refund</h3>
    <p>
      Use <a href="/support">customer support</a>. Include the order number, the product, the reason, and
      photos where they help. We will look at the request and tell you the next step.
    </p>

    <h3>6. Your statutory rights</h3>
    <p>
      Nothing in this policy limits or excludes your statutory rights under the Consumer Rights Act 2015, the
      Consumer Contracts Regulations 2013, or other UK consumer protection law.
    </p>
  </article>
</section>

