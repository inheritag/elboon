<section class="container privacy">
  <h1>Privacy</h1>
  <p class="updated">Last updated 14 November 2026.</p>
  <p>
    This policy says what personal information we collect, why we collect it, how we use it, and what you can
    ask us to do.
  </p>

  <h2>1. Shopping as a guest or creating an account</h2>
  <p>You can shop as a guest. You do not need an account.</p>
  <p>
    If you create an account, we store your email address, a hashed password, and the shipping details from
    your last order so the next checkout is shorter. We do not store the password in plain text.
  </p>

  <h2>2. Orders and delivery</h2>
  <p>When you place an order we collect what we need to process it and send it. That can include:</p>
  <ul>
    <li>Your name.</li>
    <li>Email address.</li>
    <li>Telephone number.</li>
    <li>Delivery address.</li>
    <li>What you ordered.</li>
  </ul>
  <p>
    We use this to take the order, look after it, answer questions about it, and pass the parcel to a delivery
    partner, including Royal Mail. We keep order records where we need them for accounts, tax, the law, or the
    running of the shop.
  </p>

  <h2>3. Payments</h2>
  <p>
    Payments are handled by Stripe. Elboon does not collect or store your full card number or the card
    security code. Stripe processes the payment under its own privacy and security arrangements.
  </p>

  <h2>4. Address search</h2>
  <p>
    When you type a delivery address, that text is sent to an address search that uses OpenStreetMap data, so
    we can suggest a match. We use it to make the address easier to enter. We do not keep the search itself,
    separate from the address we need to send the order.
  </p>

  <h2>5. Offers</h2>
  <p>
    If you make an offer, we store it against your email and, if you are signed in, against your account. We
    use it to tell the shop about the offer and to handle the negotiation. We do not email you about it, and
    we do not send marketing about the offer.
  </p>

  <h2>6. Customer support</h2>
  <p>
    A support message, including the email address and any order details you type, is emailed to the shop so
    we can reply. We do not put it on the site.
  </p>

  <h2>7. Who else sees it</h2>
  <p>We share personal information only where we need to, in order to run the shop. That can include:</p>
  <ul>
    <li>Stripe, to take payment.</li>
    <li>Royal Mail and other delivery partners, to send the order.</li>
    <li>The companies that host the site and keep it running.</li>
  </ul>
  <p>We do not sell personal information.</p>

  <h2>8. How long we keep it</h2>
  <p>
    We keep personal information only for as long as we reasonably need it for the purposes in this policy:
    sending orders, looking after accounts, resolving disputes, and meeting legal and accounting duties.
    Different records are kept for different lengths of time.
  </p>

  <h2>9. Your rights</h2>
  <p>Under UK data protection law you may have the right to:</p>
  <ul>
    <li>Ask for a copy of your personal information.</li>
    <li>Ask us to correct something that is wrong.</li>
    <li>Ask us to delete it.</li>
    <li>Ask us to restrict how we use it.</li>
    <li>Object to certain uses.</li>
    <li>Ask for certain information to be transferred.</li>
  </ul>
  <p>
    Contact us to use these rights. We may still need to keep some information where the law requires it, or
    where we have another lawful reason.
  </p>

  <h2>10. Contact us</h2>
  <p>
    Questions about this policy, a copy of your information, or another privacy request: use
    <a href="/support">customer support</a>.
  </p>
  <p>
    You can also complain to the Information Commissioner’s Office at
    <a href="https://ico.org.uk/">ico.org.uk</a>.
  </p>

  <h2>11. Changes</h2>
  <p>
    We may update this policy when the site, the service, or our legal duties change. The new version is
    published on this page.
  </p>
</section>

